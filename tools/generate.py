#!/usr/bin/env python3
"""Generates the dde compose files from services.yml and templates/.

Output (all generated, do not edit):
  docker-compose.yml        includes every compose/<family>.yml, defines the network
  compose/<family>.yml      the services of one family
  compose/services.tsv      one line per service for bin/dde:
                            service <TAB> mounts vhosts (0|1) <TAB> host dirs below
                            the volume base, separated by ':'

Templates are compose service definitions keyed by service name with
{{placeholders}}. Placeholders are filled from the catalog entry of a
version plus:
  {{name}}        <family>-<tag>, e.g. php-cli-83
  {{tag}}         the version key, e.g. 83
  {{env_prefix}}  the name as variable prefix, e.g. PHP_CLI_83

Template extensions resolved by the generator:
  x-binds:  ["<source>:<target>[:ro]", ...] becomes long syntax bind mounts
            with create_host_path: false. Sources not starting with '$' or '/'
            are relative to ${DOCKER_VOLUME_BASE_PATH}; a source may be
            '${VAR:-default}'. ':ro' mounts read-only.

Catalog entry keys with a meaning beyond placeholders:
  image      base image, passed as build arg BASE_IMAGE (omitted when unset,
             for contexts with a fixed FROM)
  context    build context, overrides the template's
  binds      extra x-binds entries for this version
  overrides  mapping deep-merged into the rendered service (lists replace)

Usage: tools/generate.py [--check]
  --check   do not write, exit 1 if a generated file is out of date
"""

import argparse
import copy
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "services.yml"
TEMPLATES = ROOT / "templates"
OUT_DIR = ROOT / "compose"
VHOSTS_TARGET = "/var/www/vhosts"
NETWORK = "app-tier"
HEADER = "# GENERATED by tools/generate.py from services.yml and templates/ - do not edit.\n"
PLACEHOLDER = re.compile(r"\{\{\s*([a-z_]+)\s*\}\}")


def set_root(root):
    global ROOT, CATALOG, TEMPLATES, OUT_DIR
    ROOT = root
    CATALOG = root / "services.yml"
    TEMPLATES = root / "templates"
    OUT_DIR = root / "compose"


class Dumper(yaml.SafeDumper):
    """Indents block sequences inside mappings, like hand written compose files."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def str_presenter(dumper, data):
    style = "|" if "\n" in data else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=style)


Dumper.add_representer(str, str_presenter)


def dump(data):
    return yaml.dump(data, Dumper=Dumper, sort_keys=False, default_flow_style=False, width=1000)


def space_services(text):
    """Puts an empty line between the services of a dumped compose file."""
    return re.sub(r"\n(  [^ \n][^\n]*:\n)", r"\n\n\1", text).replace("services:\n\n", "services:\n", 1)


def deep_merge(base, override):
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(base.get(key), dict):
            deep_merge(base[key], value)
        else:
            base[key] = copy.deepcopy(value)
    return base


def render(template_text, variables, where):
    def replace(match):
        key = match.group(1)
        if key not in variables or variables[key] is None:
            raise SystemExit(f"{where}: placeholder {{{{{key}}}}} has no value")
        return str(variables[key])

    return yaml.safe_load(PLACEHOLDER.sub(replace, template_text))


def expand_binds(service, extra, where):
    binds = list(service.pop("x-binds", None) or []) + list(extra or [])
    if not binds:
        return []
    volumes = service.setdefault("volumes", [])
    host_dirs = []
    for entry in binds:
        # a ${VAR:-default} source contains colons itself
        split_at = entry.find("}") + 1 if entry.startswith("${") else 0
        source, sep, rest = entry[split_at:].partition(":")
        source = entry[:split_at] + source
        target, _, mode = rest.partition(":")
        if not sep or not target.startswith(("/", "$")) or mode not in ("", "ro"):
            raise SystemExit(f"{where}: invalid bind '{entry}', expected <source>:<absolute target>[:ro]")
        if not source.startswith(("$", "/")):
            host_dirs.append(source)
            source = "${DOCKER_VOLUME_BASE_PATH}/" + source
        volume = {"type": "bind", "source": source, "target": target}
        if mode == "ro":
            volume["read_only"] = True
        volume["bind"] = {"create_host_path": False}
        volumes.append(volume)
    return host_dirs


def build_family(family, spec):
    template_file = TEMPLATES / f"{spec.get('template', family)}.yml"
    template_text = template_file.read_text()
    services = {}
    rows = []

    versions = spec.get("versions")
    if versions is None:
        # static template: rendered without version variables
        entries = [(None, {})]
    else:
        entries = list(versions.items())

    for tag, entry in entries:
        entry = dict(entry or {})
        variables = {key: value for key, value in entry.items() if not isinstance(value, (dict, list))}
        if tag is not None:
            name = f"{family}-{tag}"
            variables.update(name=name, tag=tag, family=family, env_prefix=name.upper().replace("-", "_"))
        where = f"{template_file.name} ({family}{'-' + str(tag) if tag is not None else ''})"
        rendered = render(template_text, variables, where)
        if tag is not None and list(rendered) != [variables["name"]]:
            raise SystemExit(f"{where}: a versioned template must define exactly the service {{{{name}}}}")

        for name, service in rendered.items():
            build = service.get("build")
            if build is not None:
                if entry.get("context"):
                    build["context"] = entry["context"]
                args = build.get("args") or {}
                if entry.get("image"):
                    if ":" not in entry["image"].rsplit("/", 1)[-1]:
                        raise SystemExit(f"{where}: image '{entry['image']}' needs an explicit tag")
                    args = {"BASE_IMAGE": entry["image"], **args}
                if args:
                    build["args"] = args
                else:
                    build.pop("args", None)
            host_dirs = expand_binds(service, entry.get("binds"), where)
            deep_merge(service, entry.get("overrides") or {})
            if name in services:
                raise SystemExit(f"{where}: service {name} defined twice")
            services[name] = service
            mounts_vhosts = any(
                (v.get("target") if isinstance(v, dict) else str(v).split(":")[-1]) == VHOSTS_TARGET
                for v in service.get("volumes") or []
            )
            rows.append(f"{name}\t{int(mounts_vhosts)}\t{':'.join(d for d in host_dirs if d != 'vhosts')}")
    return services, rows


def generate():
    catalog = yaml.safe_load(CATALOG.read_text())
    files = {}
    rows = []
    seen = set()
    includes = []
    for family, spec in catalog["families"].items():
        services, family_rows = build_family(family, spec or {})
        duplicates = seen & set(services)
        if duplicates:
            raise SystemExit(f"family {family}: services {sorted(duplicates)} already defined")
        seen |= set(services)
        rows += family_rows
        path = f"compose/{family}.yml"
        includes.append({"path": path, "project_directory": "."})
        files[OUT_DIR / f"{family}.yml"] = HEADER + "\n" + space_services(dump({"services": services}))

    root = {"include": includes, "networks": {NETWORK: {"driver": "bridge"}}}
    files[ROOT / "docker-compose.yml"] = HEADER + "# Edit services.yml and templates/, then run `make generate`.\n\n" + dump(root)
    files[OUT_DIR / "services.tsv"] = "".join(row + "\n" for row in rows)
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT, help="dde directory (default: this checkout)")
    args = parser.parse_args()
    set_root(args.root.resolve())

    files = generate()
    stale = [p for p in OUT_DIR.glob("*") if p.suffix in (".yml", ".tsv") and p not in files]
    outdated = [p for p, text in files.items() if not p.exists() or p.read_text() != text]

    if args.check:
        for path in outdated + stale:
            print(f"out of date: {path.relative_to(ROOT)}", file=sys.stderr)
        if outdated or stale:
            print("run `make generate` and commit the result", file=sys.stderr)
            return 1
        return 0

    OUT_DIR.mkdir(exist_ok=True)
    for path in stale:
        path.unlink()
    for path in outdated:
        path.write_text(files[path])
    print(f"generated {len(files)} files ({len(outdated)} changed, {len(stale)} removed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
